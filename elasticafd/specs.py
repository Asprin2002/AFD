"""Model and hardware specifications for the ElasticAFD simulator.

The first implementation deliberately stops at a tile/resource roofline.  Every
number in this file therefore has a physical interpretation (bytes, FLOPs, or a
measured/setup latency) and can later be replaced by a lookup table generated by
a DRAM command simulator.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from typing import Any, Mapping


GB = 1_000_000_000
TB = 1_000_000_000_000
GiB = 1 << 30


@dataclass(frozen=True)
class ModelSpec:
    name: str
    parameter_count_b: float
    layers: int
    hidden_size: int
    num_attention_heads: int
    num_kv_heads: int
    ffn_hidden_size: int
    ffn_matrices: int = 2
    dtype_bytes: int = 2
    tensor_parallel: int = 1
    data_parallel: int = 1

    def __post_init__(self) -> None:
        if self.hidden_size % self.num_attention_heads:
            raise ValueError("hidden_size must be divisible by num_attention_heads")
        if self.num_attention_heads % self.num_kv_heads:
            raise ValueError("num_attention_heads must be divisible by num_kv_heads")
        if self.ffn_matrices not in (2, 3):
            raise ValueError("ffn_matrices must be 2 (GELU) or 3 (gated FFN)")
        if self.tensor_parallel <= 0 or self.data_parallel <= 0:
            raise ValueError("tensor_parallel and data_parallel must be positive")

    @property
    def head_dim(self) -> int:
        return self.hidden_size // self.num_attention_heads

    @property
    def gqa_group_size(self) -> int:
        return self.num_attention_heads // self.num_kv_heads

    @property
    def kv_width(self) -> int:
        return self.num_kv_heads * self.head_dim

    @property
    def kv_bytes_per_token_per_layer(self) -> int:
        # K and V, each with num_kv_heads * head_dim elements.
        return 2 * self.kv_width * self.dtype_bytes

    @property
    def kv_bytes_per_token(self) -> int:
        return self.layers * self.kv_bytes_per_token_per_layer

    @property
    def q_bytes_per_token_per_layer(self) -> int:
        return self.hidden_size * self.dtype_bytes

    @property
    def output_bytes_per_token_per_layer(self) -> int:
        return self.hidden_size * self.dtype_bytes

    @property
    def new_kv_bytes_per_token_per_layer(self) -> int:
        return self.kv_bytes_per_token_per_layer

    @property
    def qkv_weight_elements_per_layer(self) -> int:
        # Q has hidden_size outputs; K and V have kv_width outputs.
        return self.hidden_size * (self.hidden_size + 2 * self.kv_width)

    @property
    def proj_ff_weight_elements_per_layer(self) -> int:
        return (
            self.output_projection_weight_elements_per_layer
            + self.ff_weight_elements_per_layer
        )

    @property
    def output_projection_weight_elements_per_layer(self) -> int:
        return self.hidden_size * self.hidden_size

    @property
    def ff_weight_elements_per_layer(self) -> int:
        return self.ffn_matrices * self.hidden_size * self.ffn_hidden_size

    @property
    def output_projection_weight_bytes_per_layer(self) -> int:
        return self.output_projection_weight_elements_per_layer * self.dtype_bytes

    @property
    def ff_weight_bytes_per_layer(self) -> int:
        return self.ff_weight_elements_per_layer * self.dtype_bytes

    @property
    def qkv_weight_bytes_per_layer(self) -> int:
        return self.qkv_weight_elements_per_layer * self.dtype_bytes

    @property
    def proj_ff_weight_bytes_per_layer(self) -> int:
        return self.proj_ff_weight_elements_per_layer * self.dtype_bytes

    @property
    def deployed_weight_bytes(self) -> float:
        # Each data-parallel replica owns one model copy. Tensor parallelism
        # shards a copy and therefore does not multiply total capacity.
        return self.parameter_count_b * 1e9 * self.dtype_bytes * self.data_parallel


@dataclass(frozen=True)
class GpuSpec:
    count: int = 8
    capacity_gib: float = 640.0
    hbm_bandwidth_tbps: float = 16.3
    fp16_tflops: float = 2496.0
    runtime_reserve_gib: float = 0.0
    # Optional experiment cap applied after weights and runtime reserve. This
    # separates "how much KV memory may the policy use?" from hardware capacity.
    kv_capacity_limit_gib: float | None = None
    # One effective-bandwidth calibration shared by both Fig.17 dense phases.
    # 0.4115 maps the published 16.3 TB/s aggregate peak to the independently
    # reported ~135 us QKV and ~405 us Proj+FF times; no per-op correction is
    # applied on top of it.
    dense_hbm_efficiency: float = 0.4115
    attention_hbm_efficiency: float = 0.70
    compute_efficiency: float = 0.80
    attention_compute_efficiency: float = 0.65
    # CHIME does not publish GPU/PIM token tile sizes.  The calibrated default
    # therefore performs no synthetic length padding; experiments may override
    # these fields for an explicit tiling sensitivity study.
    attention_tile_tokens: int = 1
    # No allocator block size is published by CHIME.  Baseline capacity is
    # token-granular; fragmentation experiments override this explicitly.
    kv_block_tokens: int = 1
    qkv_launch_us: float = 0.0
    proj_ff_launch_us: float = 0.0
    attention_launch_us: float = 2.0
    segment_setup_us: float = 0.0
    merge_launch_us: float = 1.0
    merge_request_us: float = 0.01

    def __post_init__(self) -> None:
        if self.count <= 0 or self.capacity_gib <= 0:
            raise ValueError("GPU count and capacity must be positive")
        if self.runtime_reserve_gib < 0:
            raise ValueError("GPU runtime reserve cannot be negative")
        if self.kv_capacity_limit_gib is not None and self.kv_capacity_limit_gib < 0:
            raise ValueError("GPU KV capacity limit cannot be negative")

    @property
    def capacity_bytes(self) -> float:
        return self.capacity_gib * GiB

    @property
    def bandwidth_bytes_s(self) -> float:
        return self.hbm_bandwidth_tbps * TB

    @property
    def flops_s(self) -> float:
        return self.fp16_tflops * 1e12


@dataclass(frozen=True)
class PimSpec:
    capacity_gib: float = 2048.0
    aggregate_bandwidth_tbps: float = 13.0
    ranksets: int = 4
    # CHIME interleaves KV at layer granularity across ranksets (Fig. 9).
    # Consequently one layer scans with one rankset by default, even though
    # the module-level peak quoted in Table I is the sum over four ranksets.
    # Keep this explicit so an alternative striped-layer design can be tested
    # without silently changing the CHIME baseline.
    compute_ranksets_per_layer: int = 1
    channels: int = 16
    ranks_per_channel: int = 4
    chips_per_rank: int = 8
    banks_per_chip: int = 16
    bank_hbm_efficiency: float = 1.0
    token_tile: int = 1
    kv_block_tokens: int = 1
    rank_bus_gbps_per_rankset: float = 409.6
    # No rank-softmax throughput or request setup latency is disclosed.  Zero
    # means "not separately charged" rather than inventing a fitted latency;
    # the bank/rank transfer paths remain modeled.
    softmax_gelements_s_per_rankset: float = 0.0
    request_setup_us: float = 0.0
    segment_setup_us: float = 0.0
    rankset_comm_overlap: bool = True
    relayout_efficiency: float = 1.0
    bubble_free_pipeline: bool = True
    optimized_head_mapping: bool = True
    hardware_relayout: bool = True
    cross_chip_traffic_multiplier: float = 1.0
    software_relayout_fixed_us: float = 0.0
    software_relayout_bandwidth_gbps: float = 406.0
    # Optimistic bank-PU bound for dense FP16 MAC: reading one 2-byte weight
    # enables one 2-FLOP MAC, i.e. one FLOP per byte of bank bandwidth.
    dense_mac_flops_per_byte: float = 1.0
    dense_compute_efficiency: float = 1.0

    def __post_init__(self) -> None:
        if self.ranksets <= 0:
            raise ValueError("ranksets must be positive")
        if self.ranks_per_channel != self.ranksets:
            # CHIME has one rank from every channel in each rankset.  Keeping
            # the two explicit catches accidental topology inconsistencies.
            raise ValueError("ranks_per_channel must equal ranksets")
        if not 1 <= self.compute_ranksets_per_layer <= self.ranksets:
            raise ValueError(
                "compute_ranksets_per_layer must be between 1 and ranksets"
            )

    @property
    def capacity_bytes(self) -> float:
        return self.capacity_gib * GiB

    @property
    def bandwidth_bytes_s(self) -> float:
        return self.aggregate_bandwidth_tbps * TB

    @property
    def bandwidth_per_rankset_bytes_s(self) -> float:
        return self.bandwidth_bytes_s / self.ranksets

    @property
    def layer_bandwidth_bytes_s(self) -> float:
        return (
            self.bandwidth_per_rankset_bytes_s
            * self.compute_ranksets_per_layer
        )

    @property
    def rank_bus_per_rankset_bytes_s(self) -> float:
        return self.rank_bus_gbps_per_rankset * GB

    @property
    def softmax_elements_s(self) -> float:
        return self.softmax_gelements_s_per_rankset * 1e9

    @property
    def exposed_communication_fraction(self) -> float:
        if not self.rankset_comm_overlap:
            return 1.0
        return 1.0 / self.ranksets


@dataclass(frozen=True)
class LinkSpec:
    # A single effective streaming bandwidth inferred consistently from both
    # QKV (7.2--7.4 us) and output (2.4--2.5 us) transfers in Fig.17.
    host_to_pim_gbps: float = 60.0
    pim_to_host_gbps: float = 60.0
    transfer_latency_us: float = 0.0
    full_duplex: bool = False

    @property
    def host_to_pim_bytes_s(self) -> float:
        return self.host_to_pim_gbps * GB

    @property
    def pim_to_host_bytes_s(self) -> float:
        return self.pim_to_host_gbps * GB


@dataclass(frozen=True)
class SystemSpec:
    gpu: GpuSpec = field(default_factory=GpuSpec)
    pim: PimSpec = field(default_factory=PimSpec)
    link: LinkSpec = field(default_factory=LinkSpec)

    def gpu_kv_capacity_bytes(
        self,
        model: ModelSpec,
        *,
        reclaimed_weight_bytes: float = 0.0,
    ) -> float:
        required_gpus = model.tensor_parallel * model.data_parallel
        if required_gpus != self.gpu.count:
            raise ValueError(
                f"{model.name} requires {required_gpus} GPUs for TP={model.tensor_parallel} "
                f"and DP={model.data_parallel}, but the aggregate GPU preset describes "
                f"{self.gpu.count}; partial-system deployment is not modeled"
            )
        available = (
            self.gpu.capacity_bytes
            - model.deployed_weight_bytes
            + reclaimed_weight_bytes
            - self.gpu.runtime_reserve_gib * GiB
        )
        if available < 0:
            raise ValueError(
                f"{model.name} weights require {model.deployed_weight_bytes / GiB:.1f} GiB "
                f"but GPU capacity after reserve is "
                f"{self.gpu.capacity_gib - self.gpu.runtime_reserve_gib:.1f} GiB"
            )
        available = min(self.gpu.capacity_bytes, available)
        if self.gpu.kv_capacity_limit_gib is not None:
            available = min(
                available, self.gpu.kv_capacity_limit_gib * GiB
            )
        return available

    def gpu_replica_kv_capacity_bytes(self, model: ModelSpec) -> float:
        """Usable KV capacity in one uniformly provisioned DP replica.

        ``GpuSpec`` records aggregate capacity for the whole GPU system. Model
        weights and runtime reserve are likewise aggregate quantities, so an
        even division by data parallelism gives the capacity available to a
        request-affine replica. The simulator deliberately does not let one
        replica borrow otherwise-idle memory from another.
        """

        return self.gpu_kv_capacity_bytes(model) / model.data_parallel


