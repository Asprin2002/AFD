def _normalized_key(name: str) -> str:
    return name.lower().replace("-", "").replace("_", "")


def _lookup_preset(mapping: Mapping[str, Any], name: str) -> Any:
    wanted = _normalized_key(name)
    for key, value in mapping.items():
        value_name = getattr(value, "name", key)
        if _normalized_key(key) == wanted or _normalized_key(value_name) == wanted:
            return value
    raise KeyError(f"unknown preset {name!r}; choices: {', '.join(sorted(mapping))}")


def model_from_config(raw: str | Mapping[str, Any]) -> ModelSpec:
    if isinstance(raw, str):
        return _lookup_preset(MODEL_PRESETS, raw)
    values = dict(raw)
    preset_name = values.pop("preset", None)
    if preset_name is None:
        return ModelSpec(**values)
    base = _lookup_preset(MODEL_PRESETS, str(preset_name))
    return replace(base, **values)


def system_from_config(raw: str | Mapping[str, Any]) -> SystemSpec:
    if isinstance(raw, str):
        return _lookup_preset(SYSTEM_PRESETS, raw)

    values = dict(raw)
    preset_name = values.pop("preset", "chime_a100")
    base = _lookup_preset(SYSTEM_PRESETS, str(preset_name))
    gpu = replace(base.gpu, **dict(values.pop("gpu", {})))
    pim = replace(base.pim, **dict(values.pop("pim", {})))
    link = replace(base.link, **dict(values.pop("link", {})))
    if values:
        raise TypeError(f"unknown hardware fields: {', '.join(sorted(values))}")
    return SystemSpec(gpu=gpu, pim=pim, link=link)
